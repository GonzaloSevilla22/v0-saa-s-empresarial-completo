// Paso 6: transferencia de stock entre dos sucursales desde /stock -> los dos saldos cambian; el historial muestra transfer_out / transfer_in.
import { chromium, ctxFor, open, shot, watch, rec, sql, IDS } from './humo-lib.mjs'
const ids = IDS()
const browser = await chromium.launch()
const ctx = await ctxFor(browser, 'owner')
const page = await ctx.newPage()
watch(page, 'paso6')
const S = 'paso6'
const bal = (br) => Number(sql(`select coalesce(sum(quantity),0) from branch_stock where product_id='${ids.alf}' and branch_id='${br}'`))
const a0 = bal(ids.br1), b0 = bal(ids.br2)
const nombres = sql(`select string_agg(name, ' / ' order by created_at) from branches where account_id='${ids.accA}'`)
await open(page, '/stock', 'Alfajor artesanal')
const row = page.getByText('Alfajor artesanal').filter({ visible: true }).first().locator('xpath=ancestor::*[.//button[@aria-label="Transferir stock de Alfajor artesanal"]][1]')
await row.hover()
await shot(page, `${S}-01-stock-fila-transferir`)
await row.getByRole('button', { name: 'Transferir stock de Alfajor artesanal' }).click()
const d1 = page.getByRole('dialog', { name: /transferir stock/i })
await d1.waitFor()
await d1.getByRole('button', { name: /unidades/i }).first().waitFor({ timeout: 20000 })
const origenes = await d1.getByRole('button', { name: /unidades/i }).allTextContents()
await shot(page, `${S}-02-elegir-origen`)
await d1.getByRole('button', { name: /unidades/i }).first().click()
const d2 = page.getByRole('dialog', { name: /transferir stock/i })
await d2.getByRole('combobox').waitFor()
await d2.getByRole('combobox').click()
await page.getByRole('option', { name: /sucursal norte qa/i }).click()
await d2.getByLabel(/cantidad a transferir/i).fill('5')
await shot(page, `${S}-03-formulario-transferencia`)
await d2.getByRole('button', { name: /^transferir$/i }).click()
await d2.waitFor({ state: 'detached', timeout: 60000 })
await page.waitForTimeout(1500)
const toast = await page.locator('[data-sonner-toast]').allTextContents()
const a1 = bal(ids.br1), b1 = bal(ids.br2)
const mv = sql("select string_agg(type||' '||quantity_delta||' ('||quantity_before||'->'||quantity_after||') br='||(select name from branches b where b.id=m.branch_id)||' ref='||coalesce(reference_type,'-'), ' ; ' order by movement_number) from stock_movements m where type in ('transfer_out','transfer_in')")
await shot(page, `${S}-04-tras-transferir`)
rec('6a', `/stock > Transferir stock de Alfajor artesanal: 5 u. de la sucursal de origen a "Sucursal Norte QA" (sucursales: ${nombres})`, 'Los dos saldos cambian (origen -5, destino +5)', `origen ${a0} -> ${a1}; destino ${b0} -> ${b1}; orígenes ofrecidos: ${origenes.join(' | ')}; toast: ${toast.join(' | ')}`, a1 === a0 - 5 && b1 === b0 + 5, `${S}-01-stock-fila-transferir.png, ${S}-02-elegir-origen.png, ${S}-03-formulario-transferencia.png, ${S}-04-tras-transferir.png`)
await page.getByText('Historial de movimientos').first().click()
await page.getByText(/Transferencia sal\./).first().waitFor({ timeout: 30000 }).catch(() => {})
const outV = await page.getByText(/Transferencia sal\./).filter({ visible: true }).count()
const inV = await page.getByText(/Transferencia ent\./).filter({ visible: true }).count()
await page.getByText(/Transferencia sal\./).first().scrollIntoViewIfNeeded().catch(() => {})
await shot(page, `${S}-05-historial-transferencia`)
rec('6b', '/stock > Historial de movimientos tras la transferencia', 'El historial muestra transfer_out y transfer_in', `movimientos en BD: ${mv}; filas visibles "Transferencia sal."=${outV}, "Transferencia ent."=${inV}`, outV >= 1 && inV >= 1 && /transfer_out -5/.test(mv) && /transfer_in 5/.test(mv), `${S}-05-historial-transferencia.png`)
await browser.close()
