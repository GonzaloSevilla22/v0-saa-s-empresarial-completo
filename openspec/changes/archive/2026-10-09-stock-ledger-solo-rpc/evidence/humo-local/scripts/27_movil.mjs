// Capturas a 375 px: modal de ajuste con motivo vacío y formulario de producto en edición (rol owner), más /stock del seller. Con medición de desborde.
import { chromium, ctxFor, open, shot, watch, rec } from './humo-lib.mjs'
import { measureOverflow } from './pw-lib.mjs'
const browser = await chromium.launch()
const S = 'movil375'
const ctx = await ctxFor(browser, 'owner', 'mobile')
const page = await ctx.newPage()
watch(page, 'movil')
await open(page, '/stock', 'Tomate perita')
await page.getByRole('button', { name: /^ajustar$/i }).first().click()
const dialog = page.getByRole('dialog', { name: /ajuste de inventario/i })
await dialog.waitFor()
await dialog.getByRole('combobox').filter({ hasText: /seleccioná un producto/i }).click()
await page.getByRole('option', { name: /tomate perita/i }).click()
await dialog.getByPlaceholder('Cantidad…').fill('3')
await page.waitForTimeout(400)
const disabled = await dialog.getByRole('button', { name: /registrar ajuste/i }).isDisabled()
const errTxt = (await dialog.locator('#adj-reason-error').textContent().catch(() => ''))?.trim()
const ov1 = await measureOverflow(page)
await shot(page, `${S}-01-modal-ajuste-motivo-vacio`)
rec('9a', '375 px, owner: /stock > Ajustar con motivo vacío', 'Envío bloqueado con mensaje, sin desborde horizontal', `Registrar ajuste deshabilitado=${disabled}; mensaje="${errTxt}"; desborde de documento=${ov1.docOverflow}px`, disabled && !!errTxt && ov1.docOverflow <= 1, `${S}-01-modal-ajuste-motivo-vacio.png`)
await page.keyboard.press('Escape')
await dialog.waitFor({ state: 'detached' }).catch(() => {})

await open(page, '/productos', 'Tomate perita')
const holder = page.getByText('Tomate perita').filter({ visible: true }).first().locator('xpath=ancestor::*[.//button[.//*[contains(@class,"lucide-pencil")]]][1]')
await holder.locator('button:has(.lucide-pencil)').first().click()
const edit = page.getByRole('dialog', { name: /editar producto/i })
await edit.waitFor(); await page.waitForTimeout(800)
await edit.getByText('Stock actual', { exact: true }).scrollIntoViewIfNeeded()
const btn = await edit.getByRole('button', { name: /^ajustar stock$/i }).count()
const val = (await edit.getByTestId('current-stock').textContent())?.trim()
const ov2 = await measureOverflow(page)
await shot(page, `${S}-02-producto-edicion`)
rec('9b', '375 px, owner: /productos > editar Tomate perita', '"Stock actual" + botón "Ajustar stock", sin desborde horizontal', `Stock actual="${val}"; botón "Ajustar stock"=${btn}; desborde de documento=${ov2.docOverflow}px`, btn === 1 && ov2.docOverflow <= 1, `${S}-02-producto-edicion.png`)
await ctx.close()

const ctx2 = await ctxFor(browser, 'seller', 'mobile')
const p2 = await ctx2.newPage()
watch(p2, 'movil-seller')
await open(p2, '/stock', 'Tomate perita')
const aj = await p2.getByRole('button', { name: /ajustar/i }).count()
const imp = await p2.getByRole('button', { name: /importar ajuste/i }).count()
const ov3 = await measureOverflow(p2)
await shot(p2, `${S}-03-stock-seller`)
rec('9c', '375 px, seller: /stock', 'Sin acciones de ajuste ni "Importar ajuste", sin desborde horizontal', `botones "ajustar"=${aj}; "Importar ajuste"=${imp}; desborde de documento=${ov3.docOverflow}px`, aj === 0 && imp === 0 && ov3.docOverflow <= 1, `${S}-03-stock-seller.png`)
await browser.close()
