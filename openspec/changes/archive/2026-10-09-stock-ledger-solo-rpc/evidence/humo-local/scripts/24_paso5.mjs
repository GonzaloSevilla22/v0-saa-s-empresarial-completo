// Paso 5: venta y compra de prueba y borrado de ambas -> el stock vuelve (la reversa interna anda sin EXECUTE de la app sobre rpc_reverse_stock_movement).
import { chromium, ctxFor, open, shot, watch, rec, sql, log } from './humo-lib.mjs'
const browser = await chromium.launch()
const ctx = await ctxFor(browser, 'owner')
const page = await ctx.newPage()
watch(page, 'paso5')
const S = 'paso5'
const total = () => Number(sql("select coalesce(sum(bs.quantity),0) from branch_stock bs join products p on p.id=bs.product_id where p.sku='HUMO-LOCAL-1'"))
const movSummary = () => sql("select string_agg(type||'/'||coalesce(reference_type,'-')||' '||quantity_delta||' ('||quantity_before||'->'||quantity_after||')', ' ; ' order by movement_number) from stock_movements where product_name='Producto humo local' and type <> 'adjustment'")
const confirmDelete = async (label) => {
  const dlg = page.getByRole('alertdialog').or(page.getByRole('dialog')).last()
  await dlg.waitFor({ timeout: 15000 })
  log('20_dialogos_borrado.log', `[${label}] ${(await dlg.ariaSnapshot()).replace(/\n/g, ' | ').slice(0, 400)}`)
  await shot(page, `${S}-${label}-confirmar-borrado`)
  await dlg.getByRole('button', { name: /^eliminar|^borrar|^confirmar|^sí/i }).first().click()
}

// ── Venta ──
const t0 = total()
await open(page, '/ventas')
await page.getByRole('button', { name: /nueva venta/i }).first().click()
let d = page.getByRole('dialog'); await d.waitFor(); await page.waitForTimeout(1200)
await d.getByRole('combobox').filter({ hasText: /seleccionar producto/i }).click()
await page.getByRole('option', { name: /producto humo local/i }).click()
await d.getByRole('spinbutton', { name: 'Cantidad' }).fill('2')
await d.getByRole('button', { name: /agregar al carrito/i }).click()
await d.getByRole('combobox').filter({ hasText: /seleccionar cliente/i }).click()
await page.getByRole('option', { name: /cliente humo local/i }).click()
await shot(page, `${S}-01-venta-carrito`)
await d.getByRole('button', { name: /^confirmar venta/i }).click()
await d.waitFor({ state: 'detached', timeout: 60000 })
await page.waitForTimeout(2000)
const t1 = total()
await shot(page, `${S}-02-venta-registrada`)
rec('5a', '/ventas > Nueva venta: 2 x "Producto humo local" a "Cliente humo local"', 'La venta se registra y el stock baja 2', `stock ${t0} -> ${t1}; movimientos no manuales: ${movSummary()}`, t1 === t0 - 2, `${S}-01-venta-carrito.png, ${S}-02-venta-registrada.png`)

const nSales = sql('select count(*) from sales')
await page.getByRole('button', { name: /^eliminar esta venta/i }).first().click()
await confirmDelete('venta')
await page.waitForTimeout(2500)
const t2 = total()
const salesAfter = sql('select count(*) from sales')
await shot(page, `${S}-03-venta-borrada`)
rec('5b', '/ventas > Eliminar esta venta (confirmar)', 'La venta se borra y el stock vuelve', `ventas ${nSales} -> ${salesAfter}; stock ${t1} -> ${t2}; movimientos no manuales: ${movSummary()}`, t2 === t0 && Number(salesAfter) === Number(nSales) - 1, `${S}-03-venta-borrada.png`)

// ── Compra ──
await open(page, '/compras')
await page.getByRole('button', { name: /nueva compra/i }).first().click()
d = page.getByRole('dialog'); await d.waitFor(); await page.waitForTimeout(1200)
await d.getByRole('combobox', { name: /proveedor/i }).click()
await page.getByRole('option', { name: /proveedor humo local/i }).click()
await d.getByRole('combobox').filter({ hasText: /seleccionar producto/i }).click()
await page.getByRole('option', { name: /producto humo local/i }).click()
await d.getByRole('spinbutton').first().fill('3')
await d.getByRole('button', { name: /agregar al carrito/i }).click()
await shot(page, `${S}-04-compra-carrito`)
await d.getByRole('button', { name: /^confirmar compra/i }).click()
await d.waitFor({ state: 'detached', timeout: 60000 })
await page.waitForTimeout(2000)
const t3 = total()
await shot(page, `${S}-05-compra-registrada`)
rec('5c', '/compras > Nueva compra: 3 x "Producto humo local" a "Proveedor humo local"', 'La compra se registra y el stock sube 3', `stock ${t2} -> ${t3}; movimientos no manuales: ${movSummary()}`, t3 === t2 + 3, `${S}-04-compra-carrito.png, ${S}-05-compra-registrada.png`)

const nPur = sql('select count(*) from purchases')
await page.getByRole('button', { name: /^eliminar (esta|la) compra/i }).first().click()
await confirmDelete('compra')
await page.waitForTimeout(2500)
const t4 = total()
const purAfter = sql('select count(*) from purchases')
await shot(page, `${S}-06-compra-borrada`)
rec('5d', '/compras > Eliminar la compra (confirmar)', 'La compra se borra y el stock vuelve', `compras ${nPur} -> ${purAfter}; stock ${t3} -> ${t4}; movimientos no manuales: ${movSummary()}`, t4 === t2 && Number(purAfter) === Number(nPur) - 1, `${S}-06-compra-borrada.png`)
await browser.close()
