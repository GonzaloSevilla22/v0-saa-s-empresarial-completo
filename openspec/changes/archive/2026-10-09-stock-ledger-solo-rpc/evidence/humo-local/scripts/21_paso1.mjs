// Paso 1: /stock -> "Ajustar stock" sin motivo (bloqueado) / con motivo (éxito) / historial con el motivo. Rol owner.
import { chromium, ctxFor, open, shot, watch, rec, sql, log } from './humo-lib.mjs'
const browser = await chromium.launch()
const ctx = await ctxFor(browser, 'owner')
const page = await ctx.newPage()
watch(page, 'paso1')
const S = 'paso1'
const stockAntes = sql("select quantity from branch_stock bs join products p on p.id=bs.product_id where p.sku='QA-TOMATE'")
await open(page, '/stock', 'Tomate perita')
await shot(page, `${S}-00-stock-owner`)
await page.getByRole('button', { name: /^ajustar stock$/i }).first().click()
const dialog = page.getByRole('dialog', { name: /ajuste de inventario/i })
await dialog.waitFor()
await dialog.getByRole('combobox').filter({ hasText: /seleccioná un producto/i }).click()
await page.getByRole('option', { name: /tomate perita/i }).click()
await dialog.getByPlaceholder('Cantidad…').fill('3')
await page.waitForTimeout(300)
// 1a. sin motivo -> bloqueado
const submit = dialog.getByRole('button', { name: /registrar ajuste/i })
const disabled = await submit.isDisabled()
const invalid = await dialog.getByLabel(/motivo/i).getAttribute('aria-invalid')
const errText = (await dialog.locator('#adj-reason-error').textContent().catch(() => ''))?.trim()
await shot(page, `${S}-01-modal-sin-motivo`)
rec('1a', '/stock > Ajustar stock > Tomate perita, entrada de 3, motivo vacío', 'Envío bloqueado con mensaje', `Registrar ajuste deshabilitado=${disabled}; aria-invalid=${invalid}; mensaje="${errText}"`, disabled && invalid === 'true' && !!errText, `${S}-01-modal-sin-motivo.png`)
const movAntes = sql("select count(*) from stock_movements")
// 1b. con motivo -> éxito
await dialog.getByLabel(/motivo/i).fill('Humo local: reposición por conteo')
await shot(page, `${S}-02-modal-con-motivo`)
await submit.click()
await dialog.waitFor({ state: 'detached', timeout: 60000 }).catch(() => {})
await page.waitForTimeout(1500)
await shot(page, `${S}-03-tras-ajuste`)
const stockDespues = sql("select quantity from branch_stock bs join products p on p.id=bs.product_id where p.sku='QA-TOMATE'")
const mov = sql("select type||' | delta '||quantity_delta||' | '||coalesce(reason,'NULL')||' | before '||coalesce(quantity_before::text,'-')||' after '||coalesce(quantity_after::text,'-') from stock_movements order by created_at desc limit 1")
rec('1b', 'Mismo modal, motivo "Humo local: reposición por conteo", enviar', 'Éxito: el saldo sube 3 y se registra el movimiento con motivo', `stock ${stockAntes} -> ${stockDespues}; movimientos ${movAntes} -> ${sql('select count(*) from stock_movements')}; último: ${mov}`, Number(stockDespues) === Number(stockAntes) + 3 && /Humo local/.test(mov), `${S}-02-modal-con-motivo.png, ${S}-03-tras-ajuste.png`)
// 1c. historial
await page.getByText('Historial de movimientos').first().click()
await page.getByText('Humo local: reposición por conteo').first().waitFor({ timeout: 30000 }).catch(() => {})
await page.waitForTimeout(800)
const visible = await page.getByText('Humo local: reposición por conteo').filter({ visible: true }).count()
await page.getByText('Humo local: reposición por conteo').first().scrollIntoViewIfNeeded().catch(() => {})
await shot(page, `${S}-04-historial-con-motivo`)
rec('1c', '/stock > Historial de movimientos', 'El ajuste aparece con el motivo', `filas visibles con el motivo=${visible}`, visible >= 1, `${S}-04-historial-con-motivo.png`)
await browser.close()
