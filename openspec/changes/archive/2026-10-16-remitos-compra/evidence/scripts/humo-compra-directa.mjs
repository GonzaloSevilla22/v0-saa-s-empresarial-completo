// Regresión: compra directa por /compras (SupplierSelect extraído de purchase-form): sigue sumando stock con movimiento purchase/purchase.
import { readFileSync } from 'node:fs'
import { chromium, BASE, newCtx, login as uiLogin, consoleCollector } from './pw-lib.mjs'
import { sql, check, results, USERS } from './lib.mjs'
const IDS = JSON.parse(readFileSync('C:/Users/Usuario/Desktop/EIE/scratchpad-remitos-compra/ids.json', 'utf8'))
const { accA, br1, alf, sup2 } = IDS
const stock = (pid, br) => Number(sql(`select coalesce(sum(quantity),0) from branch_stock where product_id='${pid}' and branch_id='${br}'`))
const AUTH = 'C:/Users/Usuario/Desktop/EIE/scratchpad-remitos-compra/qa-auth-owner.json'
const browser = await chromium.launch()
await uiLogin(browser, ...USERS.owner, AUTH)
const ctx = await newCtx(browser, 'desktop', 'light', AUTH)
const page = await ctx.newPage()
const errs = consoleCollector(page)
const s0 = stock(alf, br1)
const p0 = Number(sql(`select count(*) from purchases where account_id='${accA}'`))
await page.goto(`${BASE}/compras`, { waitUntil: 'domcontentloaded', timeout: 180000 })
await page.getByRole('button', { name: /Nueva compra/ }).first().click()
const d = page.getByRole('dialog')
await d.getByText('Agregar producto', { exact: false }).first().waitFor({ timeout: 60000 })
await page.waitForTimeout(1500)
await d.getByRole('combobox', { name: /Proveedor/ }).click()
await page.waitForTimeout(500)
await page.getByRole('option', { name: /Proveedor Dos QA/ }).first().click()
await d.getByRole('combobox').filter({ hasText: 'Seleccionar producto' }).click()
await page.waitForTimeout(500)
await page.getByRole('option', { name: /Alfajor artesanal/ }).first().click()
await d.getByRole('button', { name: 'Agregar al carrito' }).click()
await page.screenshot({ path: 'C:/Users/Usuario/Desktop/EIE/scratchpad-remitos-compra/capturas/compra-directa-form-desktop-light.png' })
await d.getByRole('button', { name: /Confirmar compra/ }).click()
await page.waitForTimeout(6000)
const p1 = Number(sql(`select count(*) from purchases where account_id='${accA}'`))
check('(compra directa) se registra la compra por el formulario con el proveedor elegido en SupplierSelect', p1 === p0 + 1 && sql(`select supplier_id from purchases where account_id='${accA}' order by created_at desc limit 1`) === sup2, `${p0}->${p1}`)
check('(compra directa) el stock SUBE 1', stock(alf, br1) === s0 + 1, `${s0}->${stock(alf, br1)}`)
const mv = sql(`select string_agg(distinct type||'/'||reference_type, ',') from stock_movements where reference_id in (select id from purchases where account_id='${accA}' order by created_at desc limit 1)`)
check('(compra directa) el movimiento es purchase/purchase (no de remito)', /purchase\/purchase/.test(mv), mv)
console.log('console errors:', JSON.stringify(errs.slice(0, 4)))
const failed = results.filter(([, ok]) => !ok)
console.log(`RESUMEN compra directa: ${results.length - failed.length}/${results.length} PASS`)
await browser.close()
