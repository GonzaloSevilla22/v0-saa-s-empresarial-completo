// Paso 3: /productos > editar Tomate perita: "Stock actual" sólo lectura + "Ajustar stock" con producto preseleccionado.
// Paso 4: /productos > alta de un producto nuevo con stock inicial -> historial "Stock inicial".
import { chromium, ctxFor, open, shot, watch, rec, sql, log } from './humo-lib.mjs'
const browser = await chromium.launch()
const ctx = await ctxFor(browser, 'owner')
const page = await ctx.newPage()
watch(page, 'paso3-4')
const putBodies = []
page.on('request', (r) => { if (/\/products(\/|$|\?)/.test(new URL(r.url()).pathname) && ['PUT', 'PATCH', 'POST'].includes(r.method())) putBodies.push(`${r.method()} ${new URL(r.url()).pathname} ${(r.postData() || '').slice(0, 400)}`) })
const stockOf = (sku) => sql(`select coalesce(sum(bs.quantity),0) from branch_stock bs join products p on p.id=bs.product_id where p.sku='${sku}'`)

// ── Paso 3 ──
let S = 'paso3'
await open(page, '/productos', 'Tomate perita')
const holder = page.getByText('Tomate perita').filter({ visible: true }).first().locator('xpath=ancestor::*[.//button[.//*[contains(@class,"lucide-pencil")]]][1]')
await holder.locator('button:has(.lucide-pencil)').first().click()
const edit = page.getByRole('dialog', { name: /editar producto/i })
await edit.waitFor()
await page.waitForTimeout(800)
const stockInputs = await edit.getByLabel(/^stock inicial$/i).count()
const stockActualTxt = (await edit.getByTestId('current-stock').textContent())?.trim()
const hasLabel = await edit.getByText('Stock actual', { exact: true }).count()
const btn = edit.getByRole('button', { name: /^ajustar stock$/i })
const btnCount = await btn.count()
await shot(page, `${S}-01-edicion-stock-actual`)
rec('3a', '/productos > editar Tomate perita', '"Stock actual" sólo lectura (sin input de stock) y botón "Ajustar stock"', `etiqueta "Stock actual"=${hasLabel}; valor="${stockActualTxt}"; input "Stock inicial"=${stockInputs}; botones "Ajustar stock"=${btnCount}`, hasLabel === 1 && stockInputs === 0 && btnCount === 1, `${S}-01-edicion-stock-actual.png`)

const before = stockOf('QA-TOMATE')
await btn.click()
const adj = page.getByRole('dialog', { name: /ajuste de inventario/i })
await adj.waitFor()
await page.waitForTimeout(600)
const preselected = await adj.getByText('Tomate perita', { exact: true }).count()
const stockCardTxt = (await adj.getByText(/^Stock actual: /).first().textContent().catch(() => ''))?.trim()
await shot(page, `${S}-02-modal-producto-preseleccionado`)
rec('3b', 'Edición > Ajustar stock', 'Abre el modal con el producto preseleccionado', `producto "Tomate perita" ya elegido en el modal=${preselected}; tarjeta: "${stockCardTxt}"`, preselected >= 1 && /Stock actual/.test(stockCardTxt), `${S}-02-modal-producto-preseleccionado.png`)

await adj.getByPlaceholder('Cantidad…').fill('2')
await adj.getByLabel(/motivo/i).fill('Humo local: ajuste desde la edición de producto')
await adj.getByRole('button', { name: /registrar ajuste/i }).click()
await adj.waitFor({ state: 'detached', timeout: 60000 })
await page.waitForTimeout(1500)
const after = stockOf('QA-TOMATE')
const liveTxt = (await edit.getByTestId('current-stock').textContent())?.trim()
const lastMov = sql("select type||' | '||quantity_delta||' | '||coalesce(reason,'NULL')||' | before '||quantity_before||' after '||quantity_after from stock_movements order by movement_number desc limit 1")
await shot(page, `${S}-03-tras-ajuste-desde-edicion`)
rec('3c', 'Modal: entrada de 2 con motivo, registrar', 'El saldo cambia (BD y "Stock actual" del formulario)', `BD ${before} -> ${after}; "Stock actual" del formulario="${liveTxt}"; movimiento: ${lastMov}`, Number(after) === Number(before) + 2 && lastMov.includes('Humo local: ajuste desde la edición'), `${S}-03-tras-ajuste-desde-edicion.png`)

// Guardar el formulario sin tocar el stock: el cuerpo del PUT no debe llevar `stock`.
const nPrev = putBodies.length
await edit.getByRole('button', { name: /actualizar producto/i }).click()
await page.waitForTimeout(2500)
const newReqs = putBodies.slice(nPrev)
const stockSent = newReqs.some((b) => /"stock"\s*:/.test(b))
const afterSave = stockOf('QA-TOMATE')
log('20_requests_producto.log', { paso: '3d', requests: newReqs })
rec('3d', 'Edición > Actualizar producto (sin tocar nada)', 'La edición NO manda `stock` y el saldo no cambia', `requests=${newReqs.length}; mandó "stock"=${stockSent}; saldo ${after} -> ${afterSave}`, newReqs.length >= 1 && !stockSent && Number(afterSave) === Number(after), '')

// ── Paso 4 ──
S = 'paso4'
await open(page, '/productos', 'Tomate perita')
await page.getByRole('button', { name: /nuevo producto/i }).first().click()
const nuevo = page.getByRole('dialog', { name: /nuevo producto/i })
await nuevo.waitFor()
await page.waitForTimeout(800)
await nuevo.getByPlaceholder('Ej: Remera AFA - Talle S').fill('Producto humo local')
await nuevo.getByRole('combobox').filter({ hasText: /seleccionar categoría/i }).click()
await page.getByRole('option', { name: 'Alimentos' }).click()
await nuevo.getByLabel(/^sku/i).fill('HUMO-LOCAL-1')
await nuevo.getByLabel(/^costo$/i).fill('100')
await nuevo.getByLabel(/^precio$/i).fill('250')
await nuevo.getByLabel(/^stock inicial$/i).fill('7')
await shot(page, `${S}-01-alta-con-stock-inicial`)
const nMov0 = sql('select count(*) from stock_movements')
await nuevo.getByRole('button', { name: /crear producto/i }).click()
await nuevo.waitFor({ state: 'detached', timeout: 60000 }).catch(() => {})
await page.waitForTimeout(2000)
const created = sql("select count(*) from products where sku='HUMO-LOCAL-1'")
const stk = stockOf('HUMO-LOCAL-1')
const mv = sql("select type||' | '||quantity_delta||' | '||coalesce(reason,'-')||' | ref '||coalesce(reference_type,'-')||' | by '||coalesce(performed_by::text,'-')||' | branch '||coalesce(branch_id::text,'-') from stock_movements where product_name='Producto humo local' order by movement_number desc limit 1")
await shot(page, `${S}-02-tras-crear`)
await open(page, '/stock', 'Producto humo local')
await page.getByText('Historial de movimientos').first().click()
await page.getByText('Stock inicial').filter({ visible: true }).first().waitFor({ timeout: 30000 }).catch(() => {})
const histVis = await page.getByText('Stock inicial').filter({ visible: true }).count()
await page.getByText('Stock inicial').filter({ visible: true }).first().scrollIntoViewIfNeeded().catch(() => {})
await shot(page, `${S}-03-historial-stock-inicial`)
rec('4', '/productos > Nuevo producto "Producto humo local" con stock inicial 7', 'Se crea y el historial muestra "Stock inicial"', `producto creado=${created}; saldo=${stk}; movimiento: ${mv}; "Stock inicial" visible en el historial=${histVis}`, created === '1' && Number(stk) === 7 && /^adjustment \| 7\.0000 \| Stock inicial/.test(mv) && histVis >= 1, `${S}-01-alta-con-stock-inicial.png, ${S}-02-tras-crear.png, ${S}-03-historial-stock-inicial.png`)
await browser.close()
